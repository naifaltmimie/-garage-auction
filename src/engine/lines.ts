const MOMENT_MAP: Record<string, CalloutKey> = {
  opening: 'open_bid', raising: 'who_more', bidding_war: 'war', long_silence: 'silence', price_drop: 'no_bid',
  going_once: 'going_1', going_twice: 'going_2', sold: 'sold', no_sale: 'unsold', big_bargain: 'bargain', overpaid: 'robbed',
};
for (const x of AUCT_EXTRA) {
  const key = MOMENT_MAP[x.m];
  if (!key) continue;
  const buyerKeys: CalloutKey[] = ['sold', 'bargain', 'robbed'];
  const t = buyerKeys.includes(key) ? x.t.replace(/\{name\}/g, '{buyer}') : x.t;
  // going calls stay short so the text matches the voice clip
  if (key === 'going_1' || key === 'going_2') continue;
  (AUCTIONEER[key] ??= []).push(t);
}

