"""Generates src/ui/components/plateGlyphs.ts: the Saudi plate's characters as SVG path data, so the plate draws as
one <svg> with no font loading and looks the same on every phone.

Faces (all SIL OFL 1.1, files and licences in ./fonts):
  - D-DIN PRO Medium: the Latin digits and letters (the real plate uses DIN 1451 Mittelschrift)
  - Noto Naskh Arabic Bold: the Arabic-Indic digits, the 17 plate letters and «السعودية»
  - Arimo Bold: K, S, A on the strip

Every glyph is normalised to 1000 units per em, y pointing down, baseline at y = 0.
Run: python3 scripts/brand/plate/gen_glyphs.py
"""
import json, os
import sys
import uharfbuzz as hb
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from emblem import emblem_path  # noqa: E402
OUT = os.path.join(HERE, '..', '..', '..', 'src', 'ui', 'components', 'plateGlyphs.ts')
FONTS = os.path.join(HERE, 'fonts')
DIN = os.path.join(FONTS, 'D-DIN-PRO-500-Medium.ttf')
NASKH = os.path.join(FONTS, 'noto-naskh-arabic-arabic-700-normal.woff')
ARIMO = os.path.join(FONTS, 'arimo-latin-700-normal.woff')

AR_LETTERS = ['ا', 'ب', 'ح', 'د', 'ر', 'س', 'ص', 'ط', 'ع', 'ق', 'ك', 'ل', 'م', 'ن', 'هـ', 'و', 'ى']
EN_LETTERS = ['A', 'B', 'J', 'D', 'R', 'S', 'X', 'T', 'E', 'G', 'K', 'L', 'Z', 'N', 'H', 'U', 'V']
AR_DIGITS = '٠١٢٣٤٥٦٧٨٩'


class Face:
    def __init__(self, path):
        self.tt = TTFont(path)
        self.upm = self.tt['head'].unitsPerEm
        self.k = 1000 / self.upm
        self.gs = self.tt.getGlyphSet()
        self.order = self.tt.getGlyphOrder()
        data = open(path, 'rb').read()
        if data[:4] == b'wOFF':
            # harfbuzz reads woff1 poorly; hand it the decompressed sfnt
            import io
            buf = io.BytesIO()
            self.tt.flavor = None
            self.tt.save(buf)
            data = buf.getvalue()
            self.tt = TTFont(io.BytesIO(data))
            self.gs = self.tt.getGlyphSet()
        self.hbfont = hb.Font(hb.Face(hb.Blob(data)))

    def cap(self):
        return self.tt['OS/2'].sCapHeight * self.k

    def draw(self, pen_target, gname, dx=0.0):
        k = self.k
        self.gs[gname].draw(TransformPen(pen_target, (k, 0, 0, -k, dx * k, 0)))

    def shape(self, text, rtl=False):
        buf = hb.Buffer()
        buf.add_str(text)
        buf.guess_segment_properties()
        if rtl:
            buf.direction = 'rtl'
        hb.shape(self.hbfont, buf, {})
        return [(self.tt.getGlyphName(i.codepoint), p.x_advance, p.x_offset, p.y_offset) for i, p in zip(buf.glyph_infos, buf.glyph_positions)]

    def glyph(self, items):
        """items: list of (glyph name, advance, x offset, y offset) in font units, drawn left to right."""
        pen = SVGPathPen(self.gs, ntos=lambda v: ('%.1f' % v).rstrip('0').rstrip('.'))
        bp = BoundsPen(self.gs)
        x = 0
        for g, adv, xo, yo in items:
            k = self.k
            t = (k, 0, 0, -k, (x + xo) * k, -yo * k)
            self.gs[g].draw(TransformPen(pen, t))
            self.gs[g].draw(TransformPen(bp, t))
            x += adv
        b = bp.bounds or (0, 0, 0, 0)
        return {'d': pen.getCommands(), 'w': round(x * self.k, 1), 'b': [round(v, 1) for v in b]}


def main():
    din, naskh, arimo = Face(DIN), Face(NASKH), Face(ARIMO)
    G = {}
    for ch in '0123456789':
        G['L' + ch] = din.glyph(din.shape(ch))
    for ch in EN_LETTERS:
        G['L' + ch] = din.glyph(din.shape(ch))
    for ch in AR_DIGITS:
        G['A' + ch] = naskh.glyph(naskh.shape(ch, rtl=True))
    for ch in AR_LETTERS:
        if ch == 'هـ':
            # the plate shows هـ in its initial (two-loop) form: shape it before a joiner and keep the letter only
            items = [it for it in naskh.shape('ه‍', rtl=True) if it[1] or it[0] != naskh.shape('‍')[0][0]]
            items = [items[-1]] if len(items) > 1 else items
            G['A' + ch] = naskh.glyph(items)
        else:
            G['A' + ch] = naskh.glyph(naskh.shape(ch, rtl=True))
    for ch in 'KSA':
        G['K' + ch] = arimo.glyph(arimo.shape(ch))
    # the word, shaped as one run (harfbuzz returns RTL runs in visual order, left to right)
    G['SAUDIA'] = naskh.glyph(naskh.shape('السعودية', rtl=True))
    meta = {'dinCap': round(din.cap(), 1), 'arimoCap': round(arimo.cap(), 1)}

    lines = [
        '// Generated by scripts/brand/plate/gen_glyphs.py. Do not edit by hand.',
        '// The Saudi plate\'s characters as SVG paths, 1000 units per em, y down, baseline at 0.',
        '// Outlines from: D-DIN PRO Medium (Copyright (C) 2026 CyberFei, https://github.com/CyberFei/D-DIN-PRO, SIL OFL 1.1);',
        '// Noto Naskh Arabic Bold (Copyright 2022 The Noto Project Authors, SIL OFL 1.1);',
        '// Arimo Bold (Copyright 2020 The Arimo Project Authors, SIL OFL 1.1). See docs/THIRD_PARTY.md.',
        '',
        '/** One glyph: its path, its advance and its bounds [x0, y0, x1, y1]. */',
        'export type PlateGlyph = { d: string; w: number; b: [number, number, number, number] };',
        '',
        f'export const PLATE_METRICS = {json.dumps(meta)} as const;',
        '',
        '/** Keys: L + Latin digit or letter, A + Arabic-Indic digit or Arabic letter, K + K/S/A, and SAUDIA. */',
        'export const PLATE_GLYPHS: Record<string, PlateGlyph> = {',
    ]
    for k, v in G.items():
        lines.append(f'  {json.dumps(k, ensure_ascii=False)}: {{ d: {json.dumps(v["d"])}, w: {v["w"]}, b: {json.dumps(v["b"])} }},')
    lines.append('};')
    lines += ['', '/** The national emblem as a solid silhouette, viewBox 0 0 380 420 (scripts/brand/plate/emblem.py). */', f'export const PLATE_EMBLEM = {json.dumps(emblem_path())};']
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    print('wrote', OUT, os.path.getsize(OUT), 'bytes', meta)
    for k in ['A٥', 'Aط', 'Aهـ', 'Aى', 'L5', 'LR', 'KK', 'SAUDIA']:
        print(k, G[k]['w'], G[k]['b'])


if __name__ == '__main__':
    main()
