// Emits the two small tables a player's phone needs, so it never downloads the car market:
//   src/data/showroom.ts  ~40 real cars for Home's front page (each with its checked outside photo)
//   src/data/depth.ts     how many real ads each market holds at a budget (Create / Lobby counts)
// Run after the catalogue or photos change:  npx tsx scripts/build_showroom.ts
import { writeFileSync } from 'node:fs';
import { CATALOGUE, PHOTOS, loadMarket } from '../src/data/market';
import { bucketOf, marketDepth } from '../src/engine/lotgen';
import { MARKETS } from '../src/engine/markets';
import { BUDGETS, DEFAULT_SETTINGS, GARAGE_SIZES } from '../src/engine/rules';
import type { CarModel } from '../src/engine/types';

await loadMarket();

// --- showroom ------------------------------------------------------------------------------------
const SIZE = 40;
// same rule as Home always used: only ads whose first photo was checked to be the outside of the car
const coverOf = (id: string) => PHOTOS[id]?.find((a) => a.ext && a.imgs.length);
const pool = CATALOGUE.filter((m) => coverOf(m.id)).sort(() => Math.random() - 0.5);
// a spread of tiers, so Home's own pick of 8 (one per tier first) always has every tier to draw from
const out: CarModel[] = [];
for (let round = 0; round < 3 && out.length < SIZE; round++) {
  const seen = new Set<string>();
  for (const m of pool) {
    if (out.length >= SIZE) break;
    if (seen.has(m.tier) || out.includes(m)) continue;
    seen.add(m.tier);
    out.push(m);
  }
}
for (const m of pool) if (out.length < SIZE && !out.includes(m)) out.push(m);
const cars = out.map((m) => ({ id: m.id, makeAr: m.makeAr, modelAr: m.modelAr, year: m.year, value: m.value, tier: m.tier, img: coverOf(m.id)!.imgs[0] }));

writeFileSync(
  new URL('../src/data/showroom.ts', import.meta.url),
  `// GENERATED by scripts/build_showroom.ts from catalogue.ts + photos.ts — do not edit by hand.
// ${cars.length} real cars for Home's front page, so a player's phone never loads the whole market.
import type { Tier } from '../engine/types';

export interface ShowCar {
  id: string;
  makeAr: string;
  modelAr: string;
  year: number;
  value: number;
  tier: Tier;
  /** the ad's first photo, checked to be the outside of the car */
  img: string;
}

export const SHOWROOM: ShowCar[] = [
${cars.map((c) => `  ${JSON.stringify(c)},`).join('\n')}
];
`,
);

// --- market depth --------------------------------------------------------------------------------
// marketDepth counts the distinct ads (3+ photos) a market holds that a budget can reach. Exact at every
// preset budget; for a custom one, the cheapest ads per market are enough, since a night never deals
// more than 40 lots and the Lobby shows min(lots, depth).
const LOW = 64;
const budgets = [...new Set([...BUDGETS.map((b) => b.amount), ...MARKETS.map((m) => m.budget)])].sort((a, b) => a - b);
const at: Record<string, Record<number, number>> = {};
const low: Record<string, number[]> = {};
for (const mk of MARKETS) {
  at[mk.id] = {};
  for (const budget of budgets) at[mk.id][budget] = marketDepth({ ...DEFAULT_SETTINGS, mix: mk.id, budget }, CATALOGUE);
  // each ad at the cheapest value it is listed at in this market
  const best = new Map<string, number>();
  for (const m of CATALOGUE) {
    if (!mk.test(m)) continue;
    for (const a of PHOTOS[m.id] ?? []) {
      if (a.imgs.length < 3) continue;
      const v = a.value ?? m.value;
      best.set(a.key, Math.min(best.get(a.key) ?? Infinity, v));
    }
  }
  low[mk.id] = [...best.values()].sort((a, b) => a - b).slice(0, LOW);
}

// the lite count must agree with the real one wherever we can check it
const lite = (mix: string, budget: number) => {
  const n = low[mix].filter((v) => v <= budget * 0.92).length;
  return n;
};
let checked = 0;
for (const mk of MARKETS) {
  for (const budget of [...budgets, 50_000, 120_000, 200_000, 450_000, 1_000_000, 2_250_000, 7_500_000]) {
    for (const garage of GARAGE_SIZES) {
      const s = { ...DEFAULT_SETTINGS, mix: mk.id, budget, garage };
      const real = marketDepth(s, CATALOGUE);
      // bucketOf only drops a car the budget can't reach, whatever the garage size
      const reach = low[mk.id].every((v) => (bucketOf(v, budget / garage, budget) !== null) === (v <= budget * 0.92));
      const l = lite(mk.id, budget);
      const ok = reach && (budget in at[mk.id] ? at[mk.id][budget] === real : l < LOW ? l === real : real >= LOW);
      if (!ok) throw new Error(`depth mismatch: ${mk.id} ${budget} ${garage}: real ${real}, lite ${l}`);
      checked++;
    }
  }
}

writeFileSync(
  new URL('../src/data/depth.ts', import.meta.url),
  `// GENERATED by scripts/build_showroom.ts from catalogue.ts + photos.ts — do not edit by hand.
// How many different real ads each market holds at a budget (lotgen's marketDepth), without the market.
import type { Settings } from '../engine/types';

/** exact counts at every preset budget */
const AT: Record<string, Record<number, number>> = ${JSON.stringify(at)};

/** the ${LOW} cheapest ads' values per market: enough for any custom budget, since a night deals at most 40 lots */
const LOW: Record<string, number[]> = ${JSON.stringify(low)};

/** Same number as marketDepth(settings, CATALOGUE); above ${LOW} only at the preset budgets (custom budgets cap at ${LOW}). */
export function depthOf(s: Pick<Settings, 'mix' | 'budget'>): number {
  const mix = s.mix in AT ? s.mix : 'balanced';
  const exact = AT[mix][s.budget];
  if (exact !== undefined) return exact;
  return LOW[mix].filter((v) => v <= s.budget * 0.92).length;
}
`,
);

console.log(`showroom: ${cars.length} cars (${new Set(cars.map((c) => c.tier)).size} tiers); depth: ${MARKETS.length} markets × ${budgets.length} budgets, ${checked} checks passed`);
