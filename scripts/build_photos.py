#!/usr/bin/env python3
"""research/haraj_ads.json -> src/data/photos.ts (real ad photo sets per catalogue model)."""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else Path('/home/claude/research/haraj_ads.json')
OUT = ROOT / 'src' / 'data' / 'photos.ts'
MAX_IMGS = 8

data = json.load(open(SRC, encoding='utf-8'))
ads = data.get('ads', {})
cat_ids = set(re.findall(r'"id":"([^"]+)"', (ROOT / 'src' / 'data' / 'catalogue.ts').read_text(encoding='utf-8')))
out = {}
for mid, lst in ads.items():
    if mid not in cat_ids:
        print('skip (not in catalogue):', mid)
        continue
    sets = []
    for a in lst:
        imgs = [u for u in (a.get('imgs') or []) if isinstance(u, str) and u.startswith('https://')]
        # drop exact duplicates, keep order
        seen = set()
        imgs = [u for u in imgs if not (u in seen or seen.add(u))][:MAX_IMGS]
        # Haraj photos are stored as their CDN path only; the app rebuilds the full-size
        # (mimg6cdn) and 700px webp (postcdn) URLs — half the bytes in the bundle.
        imgs = [('h:' + u.split('haraj.com.sa/', 1)[1]) if 'mimg6cdn.haraj.com.sa/' in u else u for u in imgs]
        if len(imgs) < 2:
            continue
        o = {'imgs': imgs}
        for k in ('city', 'color', 'km', 'price', 'title', 'url', 'text'):
            v = a.get(k)
            if v not in (None, '', 0):
                o[k] = v
        if a.get('source') and a['source'] != 'haraj':
            o['src'] = a['source']
        sets.append(o)
    if sets:
        out[mid] = sets
lines = [
    '// GENERATED by scripts/build_photos.py from research/haraj_ads.json — real ad photos per model.',
    "export interface AdSet {",
    "  imgs: string[];",
    "  city?: string | null;",
    "  color?: string | null;",
    "  km?: number | null;",
    "  price?: number | null;",
    "  title?: string;",
    "  text?: string;",
    "  url?: string;",
    "  src?: string;",
    "}",
    '',
    'export const PHOTOS: Record<string, AdSet[]> = {',
]
for mid, sets in out.items():
    lines.append(f'  {json.dumps(mid)}: {json.dumps(sets, ensure_ascii=False, separators=(",", ":"))},')
lines.append('};')
lines.append('')
OUT.write_text('\n'.join(lines), encoding='utf-8')
print('models with photos:', len(out), 'sets:', sum(len(v) for v in out.values()), 'imgs:', sum(len(s['imgs']) for v in out.values() for s in v))
