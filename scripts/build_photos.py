#!/usr/bin/env python3
"""research/haraj_ads.json -> src/data/photos.ts (real ad photo sets per catalogue model)."""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else Path('/home/claude/research/haraj_all.json')
QA = Path('/home/claude/research/cover_qa.txt')
# R|postid|catalogueId|catBody|firstExteriorBody|codes|exteriorScores — one letter per photo (see qa/classify.mjs):
# E exterior, I seats, D dashboard, O odometer, N engine, W wheel, T trunk, L lights, S screenshot/graphic,
# P paper, X person, G parts, K keys, ? failed to load
qa = {}
if QA.exists():
    for line in QA.read_text(encoding='utf-8').splitlines():
        f = line.strip().split('|')
        if len(f) >= 7 and f[0] == 'R' and f[4] != 'ERR':
            qa[f[1]] = (f[5], [int(x) / 100 for x in f[6].split(',')], f[3], f[4])
DROP_CODES = set('SPX?')
qa_report = []
OUT = ROOT / 'src' / 'data' / 'photos.ts'
MAX_IMGS = 8

data = json.load(open(SRC, encoding='utf-8'))
ads = data.get('ads', {})
cat_ids = set(re.findall(r'"id":"([^"]+)"', (ROOT / 'src' / 'data' / 'catalogue.ts').read_text(encoding='utf-8')))
out = {}
for mid, lst in ads.items():
    if mid not in cat_ids:
        print('skip (not in catalogue):', mid)
        continue
    sets = []
    for a in lst:
        imgs = [u for u in (a.get('imgs') or []) if isinstance(u, str) and u.startswith('https://')]
        # drop exact duplicates, keep order
        seen = set()
        imgs = [u for u in imgs if not (u in seen or seen.add(u))][:MAX_IMGS]
        # Haraj photos are stored as their CDN path only; the app rebuilds the full-size
        # (mimg6cdn) and 700px webp (postcdn) URLs — half the bytes in the bundle.
        imgs = [('h:' + u.split('haraj.com.sa/', 1)[1]) if 'mimg6cdn.haraj.com.sa/' in u else u for u in imgs]
        m = re.search(r'haraj\.com\.sa/(\d{8,})', a.get('url') or '')
        q = qa.get(m.group(1)) if m else None
        if q:
            codes, ext, cat_body, body = q
            keep = [(u, c, x) for u, c, x in zip(imgs, codes, ext) if c not in DROP_CODES]
            first = next((k for k, (u, c, x) in enumerate(keep) if c == 'E' and x >= 0.3), None)
            if first is None:
                qa_report.append(f'drop {m.group(1)} ({mid}): no exterior photo [{codes}]')
                continue
            if first:
                qa_report.append(f'cover {m.group(1)} ({mid}): photo {first + 1} is the first exterior [{codes}]')
            keep = [keep[first]] + keep[:first] + keep[first + 1:]
            imgs = [u for u, c, x in keep]
            bt = body.split(':')[0]
            conf = int(body.split(':')[1].split('@')[0]) if ':' in body else 0
            clash = {('sedan', 'pickup'), ('pickup', 'sedan'), ('pickup', 'hatch'), ('sedan', 'van'), ('suv', 'hatch'), ('coupe', 'pickup'),
                     ('coupe', 'van'), ('pickup', 'coupe'), ('van', 'sedan'), ('van', 'coupe')}
            if (cat_body, bt) in clash and conf >= 60:
                qa_report.append(f'body? {m.group(1)} ({mid}): catalogue {cat_body}, photo looks {bt} {conf}%')
        if len(imgs) < 2:
            continue
        o = {'imgs': imgs}
        for k in ('city', 'color', 'km', 'price', 'title', 'url', 'text'):
            v = a.get(k)
            if v not in (None, '', 0):
                o[k] = v
        if a.get('source') and a['source'] != 'haraj':
            o['src'] = a['source']
        sets.append(o)
    if sets:
        out[mid] = sets
lines = [
    '// GENERATED by scripts/build_photos.py from research/haraj_all.json (+ photo QA) — real Haraj ad photos per model.',
    "export interface AdSet {",
    "  imgs: string[];",
    "  city?: string | null;",
    "  color?: string | null;",
    "  km?: number | null;",
    "  price?: number | null;",
    "  title?: string;",
    "  text?: string;",
    "  url?: string;",
    "  src?: string;",
    "}",
    '',
    'export const PHOTOS: Record<string, AdSet[]> = {',
]
for mid, sets in out.items():
    lines.append(f'  {json.dumps(mid)}: {json.dumps(sets, ensure_ascii=False, separators=(",", ":"))},')
lines.append('};')
lines.append('')
OUT.write_text('\n'.join(lines), encoding='utf-8')
print('models with photos:', len(out), 'sets:', sum(len(v) for v in out.values()), 'imgs:', sum(len(s['imgs']) for v in out.values() for s in v))
if qa_report:
    Path('/home/claude/research/photo_qa_report.md').write_text('\n'.join(qa_report) + '\n', encoding='utf-8')
    print(f'photo QA: {len(qa)} ads checked, {sum(1 for r in qa_report if r.startswith("drop"))} dropped, '
          f'{sum(1 for r in qa_report if r.startswith("cover"))} covers moved, {sum(1 for r in qa_report if r.startswith("body?"))} body flags')
